abstract class AppFontSize {

  /// 24px → Extra Extra Extra Large
  /// 
  /// Usage:
  /// - Main headlines
  /// - Landing page titles
  /// - Hero sections
  static const double xxxl = 24;

  /// 22px → Extra Extra Large
  /// 
  /// Usage:
  /// - Screen titles
  /// - Important headings
  static const double xxl = 22;

